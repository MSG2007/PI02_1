# Жадный алгоритм для задачи о распределении ресурсов между проектами

def greedy_resource_allocation():
    """
    Функция реализует жадный алгоритм для выбора проектов, максимизирующих прибыль
    при ограниченном объёме ресурсов.

    Жадная стратегия: выбираем проекты с наибольшим отношением прибыли к требуемому ресурсу
    (прибыльность на единицу ресурса), пока хватает общего ресурса.
    """

    # Шаг 1: Ввод общего объёма доступных ресурсов
    # Используем float() для поддержки дробных значений, int() можно заменить при необходимости
    total_resource = float(input("Введите общий объём доступных ресурсов: "))

    # Шаг 2: Ввод количества проектов
    num_projects = int(input("Введите количество проектов: "))

    # Шаг 3: Создание списка для хранения данных о проектах
    # Каждый проект будет представлен в виде словаря с ключами 'resource' и 'profit'
    projects = []

    # Шаг 4: Последовательный ввод данных для каждого проекта
    for i in range(num_projects):
        print(f"\nПроект {i + 1}:")

        # Ввод требуемого ресурса для проекта
        resource = float(input("  Требуемый ресурс: "))

        # Ввод прибыли, которую приносит проект
        profit = float(input("  Прибыль: "))

        # Добавление проекта в список
        projects.append({
            'resource': resource,
            'profit': profit
        })

    # Шаг 5: Вычисление «эффективности» каждого проекта
    # Эффективность = прибыль / требуемый ресурс
    # Это ключевой жадный критерий: выбираем самые «выгодные» проекты
    for project in projects:
        project['efficiency'] = project['profit'] / project['resource']

    # Шаг 6: Сортировка проектов по убыванию эффективности
    # Самые эффективные проекты будут в начале списка
    projects.sort(key=lambda x: x['efficiency'], reverse=True)

    # Шаг 7: Инициализация переменных для отслеживания результата
    selected_projects = []  # Список выбранных проектов
    total_used_resource = 0  # Общий использованный ресурс
    total_profit = 0  # Общая полученная прибыль

    # Шаг 8: Последовательный выбор проектов по жадному критерию
    for project in projects:
        # Проверяем, хватает ли оставшегося ресурса на текущий проект
        if total_used_resource + project['resource'] <= total_resource:
            # Если хватает — добавляем проект в решение
            selected_projects.append(project)
            total_used_resource += project['resource']
            total_profit += project['profit']

    # Шаг 9: Вывод результатов
    print("\n" + "=" * 50)
    print("РЕЗУЛЬТАТЫ РАСПРЕДЕЛЕНИЯ РЕСУРСОВ")
    print("=" * 50)

    if selected_projects:
        print("Выбранные проекты:")
        for i, project in enumerate(selected_projects, 1):
            print(f"  {i}. Ресурс: {project['resource']:.2f}, "
                  f"Прибыль: {project['profit']:.2f}, "
                  f"Эффективность: {project['efficiency']:.2f}")
        print(f"\nОбщий использованный ресурс: {total_used_resource:.2f}")
        print(f"Общая прибыль: {total_profit:.2f}")
    else:
        print("Нет проектов, которые можно реализовать с заданным объёмом ресурсов.")

    print(f"Неиспользованный ресурс: {total_resource - total_used_resource:.2f}")

# Шаг 10: Запуск программы
if __name__ == "__main__":
    greedy_resource_allocation()

